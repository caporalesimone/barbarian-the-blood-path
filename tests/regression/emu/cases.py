"""Second emulator (13/11, committente): the game must also run on vc64web (VirtualC64 in WebAssembly, another core and
another 1541 emulation than VICE). VICE stays the only authoritative reference: these tests do not decide what is
correct, they check that the real disk, played like a player with joystick and keyboard only, works there too.
Package: vc64web-custom of Lab64 (image lab64-vc64web), helper: tests/lib/emu.py, guide: docs/emulatore.md.

One session, a chain (after a failure the following tests are SKIP): real boot from the disk -> LOBBY -> new barbarian
(saved with Krill's save plugin on the emulated 1541-II) -> village (HUD text read from the screen RAM) -> alchemist
(buys a portal scroll) -> crypt -> kill a monster -> portal scroll -> back in the village -> reset and boot again: the
saved hero is in the list. About 4 minutes. The bots (bots/*.js) run inside the emulator and read the game RAM through
the labels of out/work/game.lbl. SKIP (not FAIL) when the daemon (container lab64-vc64web, EMU_URL) is not running."""
import os
from c64test import test, check, Skip
from lib.c64 import OUT, ROOT
from lib.emu import Emu
from lib.play import NAME, SEED
import sys
sys.path[:0] = [os.path.join(ROOT, "tools", d) for d in ("build", "vice", "atlas", "simulators")]
import gen_gfx as GG  # noqa: E402

CHAIN = True
H = os.path.dirname(os.path.abspath(__file__))
HERO = "black thorne"                                # project rule: 12 characters with a space
SEED_TXT = "terrar"                                  # village with the alchemist at its door; the same on every run
TILE = {n: i for i, n in enumerate(GG.TILES)}
GL = {}                                              # item constants of out/work/game.lbl (`I_NAME = value`), read in setup


def js(name):
    with open(os.path.join(H, "bots", name)) as f: return f.read()


def setup(ctx):
    for f in ("disk.d64", "game.prg", "lobby.prg", "game.lbl", "lobby.lbl", "gfx_consts.inc"):
        if not os.path.isfile(os.path.join(OUT, f)): raise Skip("out/%s missing: run ./build.sh first" % f)
    for line in open(os.path.join(OUT, "game.lbl")):
        p = line.replace("\t", " ").split()
        if len(p) >= 3 and p[1] == "=" and p[0].startswith("I_"): GL[p[0]] = int(p[2][1:], 16) if p[2].startswith("$") else int(p[2])
    e = ctx["e"] = Emu()
    e.load_labels("game.lbl")
    e.load_labels("lobby.lbl", set="lobby")           # LOBBY and GAME share $C000: separate label sets


def teardown(ctx):
    if "e" in ctx: ctx["e"].close()


def find_tile(e, name):
    m = e.peek("MAP", 48 * 48)
    return [(i % 48, i // 48) for i, v in enumerate(m) if v == TILE[name]]


@test("EMU-10", "vc64web: real boot from the disk (LOAD, POKE 1020,1, RUN): START with Krill, GAME and LOBBY loaded, menu shown")
def boot(ctx):
    e = ctx["e"]
    ok, frames = e.boot()
    ctx["boot_frames"] = frames
    check(ok, "the module LOBBY never appeared in RAM (%d frames)" % frames)
    lobby = open(os.path.join(OUT, "lobby.prg"), "rb").read()
    check(bytes(e.peek(0xC000, 64)) == lobby[2:66], "the code at $C000 is not LOBBY")
    game = open(os.path.join(OUT, "game.prg"), "rb").read()
    check(bytes(e.peek(0x0400, 64)) == game[2:66], "the code at $0400 is not GAME")
    check(e.peek(0xD020) & 15 != 2, "red border (an error screen of the loader)")
    e.screenshot(os.path.join(OUT, "emu_lobby.png"))


@test("EMU-11", "vc64web: new barbarian from the menu (joystick + keyboard), saved to disk by the Krill plugin, village reached")
def create(ctx):
    e = ctx["e"]
    e.call("resume")
    e.run_script("\n".join([
        "wait 60", "0 JOY2-FIRE 3",                   # the cursor is on "create new barbarian"
        "wait 90", '0 text "%s\\n"' % HERO,           # name (12 characters, one space); W/A/S/D are letters here
        "wait 60", '0 text "%s"' % SEED_TXT,          # seed
        "wait 60", "0 RETURN", "wait 40", "0 RETURN", "wait 60"]))
    check(e.to_main_loop(timeout=4000), "main_loop not reached: the hero was not saved or the village not entered")
    e.call("resume"); e.frames(60); e.call("pause")
    check(e.peek("cur_level") == 0, "cur_level is %d, expected the village (0)" % e.peek("cur_level"))
    check(e.word("c_hp") > 0, "the new hero has no hit points")
    check(e.word("c_gold") == 100, "starting gold is %d, expected 100" % e.word("c_gold"))
    name = e.peek("c_name", 12)
    check(name == NAME, "hero name in RAM %s, expected %s" % (name, NAME))
    e.screenshot(os.path.join(OUT, "emu_village.png"))


@test("EMU-12", "vc64web: the HUD text (HP, XP, LV) is on screen in the encoding 'hud' generated by the build")
def hud(ctx):
    e = ctx["e"]
    enc = e.load_encoding("hud", os.path.join(OUT, "gfx_consts.inc"))
    check(enc.get("chars", 0) >= 40, "encoding 'hud' has only %s characters" % enc.get("chars"))
    hp = "%d/%d" % (e.word("c_hp"), e.word("hpmax"))
    for t in ("HP", "XP", "LV", hp):                 # (the level number is right-aligned: "LV  1")
        r = e.call("findText", t, {"enc": "hud", "addr": "$8400"})
        check(r, "'%s' not found in the HUD matrix ($8400)" % t)


def buy_scroll(e):
    """at the alchemist's door: open the shop and buy the portal scroll. The assortment is rolled again at every visit
    (enter_shop: frame ^ rnd): the 2 wares (portal scroll, minor healing) come in either order, in principle the scroll
    could also be missing. Read the 8 ware ids in RAM (l8_id), put the cursor on the scroll, leave and come back if it
    is not in stock. Returns (visit, ids)."""
    scroll = GL["I_PORTAL_SCROLL"]
    for visit in range(12):
        e.run_script("0 JOY2-FIRE 3\nwait 120")                  # fire at the door: the shop opens
        ids = e.peek("l8_id", 8)
        if scroll in ids: break
        e.run_script("0 RUN/STOP\nwait 60")                     # leave: the next visit rolls a new assortment
    else:
        check(False, "no portal scroll in the alchemist stock after 12 visits (last: %s)" % ids)
    idx = ids.index(scroll)
    for _ in range(idx):                                          # the cursor starts on the first ware: joystick down
        e.run_script("0 JOY2-DOWN 3\nwait 20")
    check(e.peek("ui_lc") == 12 + idx, "cursor on item %d, expected the ware %d (portal scroll)" % (e.peek("ui_lc"), idx))
    e.run_script("\n".join(["0 JOY2-FIRE 3", "wait 60",         # select
                            "0 JOY2-FIRE 3", "wait 120",        # confirm "BUY FOR 60?"
                            "0 RUN/STOP", "wait 60"]))          # leave
    return visit, ids


@test("EMU-13", "vc64web: walk to the alchemist, buy the portal scroll (60 gold): gold and pack change")
def shop(ctx):
    e = ctx["e"]
    doors = find_tile(e, "DALCH")
    check(len(doors) == 1, "alchemist door tiles: %s" % doors)
    gx, gy = doors[0][0], doors[0][1] + 1             # below the door
    e.call("resume")
    r = e.run_loop(js("lib.js") + "const GX=%d,GY=%d;\n" % (gx, gy) + js("walk.js"), frames=3000)
    st = r["state"]
    check(st.get("arrived"), "the hero did not reach the alchemist door (timeout=%s nopath=%s)" % (st.get("timeout"), st.get("nopath")))
    gold0 = e.word("c_gold")
    visit, ids = buy_scroll(e)
    e.call("pause")
    check(e.word("c_gold") == gold0 - 60, "gold %d -> %d, expected -60 (visit %d, wares %s)" % (gold0, e.word("c_gold"), visit, ids))
    check(GL["I_PORTAL_SCROLL"] in e.peek("c_pack", 4), "the portal scroll is not in the pack: %s" % e.peek("c_pack", 4))


@test("EMU-14", "vc64web: walk to the crypt stairs and go down: level 1 (generator, GFX and monsters loaded)")
def crypt(ctx):
    e = ctx["e"]
    st_ = find_tile(e, "TSTAIRS")
    check(len(st_) == 1, "crypt stairs tiles: %s" % st_)
    e.call("resume")
    r = e.run_loop(js("lib.js") + "const GX=%d,GY=%d;\n" % st_[0] + js("walk.js"), frames=6000)
    check(r["state"].get("arrived"), "the hero did not reach the crypt stairs (timeout=%s)" % r["state"].get("timeout"))
    e.run_script("0 JOY2-FIRE 3\nwait 450")
    e.call("pause")
    check(e.peek("cur_level") == 1, "cur_level is %d, expected 1" % e.peek("cur_level"))
    check(e.peek("lb_cnt") > 0, "the crypt has no monsters")
    e.screenshot(os.path.join(OUT, "emu_crypt.png"))


@test("EMU-15", "vc64web: kill a monster in the crypt, read the portal scroll, take the portal back to the village")
def portal(ctx):
    e = ctx["e"]
    e.call("resume")
    r = e.run_loop(js("lib.js") + js("hunt_portal.js"), frames=10000)
    st = r["state"]                                   # (r["exact"] is not checked: a level change reads the disk, docs/emulatore.md)
    log = " | ".join(st.get("log", []))
    check(st.get("end") == "village", "the bot ended with '%s': %s" % (st.get("end"), log))
    check(any(l.startswith("killed") for l in st["log"]), "no monster was killed: " + log)
    check(st.get("portal") == 1, "portal flag %s after the scroll: %s" % (st.get("portal"), log))
    e.call("pause")
    check(e.peek("cur_level") == 0, "cur_level is %d after the portal, expected the village" % e.peek("cur_level"))
    check(e.word("c_hp") > 0, "the hero died")


@test("EMU-16", "vc64web: reset and boot again from the same disk copy: the hero saved at creation is in the LOBBY list")
def saved(ctx):
    e = ctx["e"]
    e.call("reset")
    e.call("resume")
    e.frames(150)
    # the disk is still in the drive (the saved hero lives in the copy of the image held by the emulator)
    e.call("sendText", 'LOAD"*",8\n'); e.frames(700, fast=True)
    e.call("sendText", "POKE 1020,1\n"); e.call("sendText", "RUN\n")
    lobby = open(os.path.join(OUT, "lobby.prg"), "rb").read()
    sig = list(lobby[0x0c + 2:0x0c + 2 + 16])
    check(e.until(lambda: e.peek(0xC00C, 16) == sig, step=150, limit=9000), "LOBBY not loaded after the reset")
    e.frames(200, fast=True)
    e.call("pause")
    n = e.peek("lobby:nvalid")
    check(n == 1, "the LOBBY lists %d heroes, expected the 1 saved at creation" % n)
    check(e.peek("lobby:slot_valid") == 1, "slot 0 is not marked as valid")
    check(e.peek("lobby:slot_name", 12) == NAME, "name in slot 0: %s, expected %s" % (e.peek("lobby:slot_name", 12), NAME))
    e.screenshot(os.path.join(OUT, "emu_lobby_hero.png"))
