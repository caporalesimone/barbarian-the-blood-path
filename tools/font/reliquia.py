def build(over):
    f = F.make_font(BASE_STYLE)
    for ch, rows in V[0][1].items():   # Q ed R curate della "prima" come base comune
        f[ch] = g8(rows)
    for ch, rows in over.items():
        f[ch] = g8(rows)
    return f


def main():
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "out", "work", "font", "reliquia")   # anteprime (13/11: in out/work/font/)
    os.makedirs(out, exist_ok=True)
    F.LOREM[:] = ["LOREM IPSUM DOLOR SIT AMET,", "CONSECTETUR ADIPISCING ELIT.",
                  "QUO VADIS, REX? JUXTA KALENDAS", "WYVERN FLAMMAE ZELOTIS HIC",
                  "GOLD 2350  HP 99/117  DMG 41-61", "THE BUTCHER AWAITS BELOW!"]
    thumbs = []
    for name, over in V:
        f = build(over)
        thumbs.append(F.render_screen(f, "reliquia " + name, os.path.join(out, f"reliquia_{name.replace(' ', '_')}.png")))
    w, h = thumbs[0].size
    sheet = Image.new("RGB", (w * 2, h * 5), (20, 20, 20))
    for i, t in enumerate(thumbs):
        sheet.paste(t, ((i % 2) * w, (i // 2) * h))
    sheet.save(os.path.join(out, "reliquia_tutte.png"))
    for name, over in V:
        for ch, r in over.items():
            assert len(r) == 8 and all(len(x) == 8 for x in r), (name, ch)
    print("ok")


if __name__ == "__main__":
    main()
